-- =============================================================================
-- V1 — Estructura inicial de tablas
-- Flyway ejecuta este script PRIMERO en una BD limpia.
-- Crea las tablas base: venues y events (sin relaciones complejas aún).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Tabla: venues
-- Lugar físico donde se realizan los eventos.
-- -----------------------------------------------------------------------------
CREATE TABLE venues (
    id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(150) NOT NULL,
    address  VARCHAR(255),
    city     VARCHAR(100) NOT NULL,
    capacity INTEGER      NOT NULL CHECK (capacity > 0)
);

-- -----------------------------------------------------------------------------
-- Tabla: events
-- Evento base con soft delete (columna active).
-- La FK a venues se establece aquí desde el inicio.
-- -----------------------------------------------------------------------------
CREATE TABLE events (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    date        DATE         NOT NULL,
    description TEXT,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    venue_id    BIGINT       NOT NULL,

    CONSTRAINT fk_events_venue
        FOREIGN KEY (venue_id) REFERENCES venues(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Índice sobre active para que @SQLRestriction filtre eficientemente
CREATE INDEX idx_events_active   ON events(active);
-- Índice sobre date para ordenamiento DESC eficiente (Escenario 2)
CREATE INDEX idx_events_date     ON events(date DESC);
-- Índice sobre venue_id para JOINs frecuentes
CREATE INDEX idx_events_venue_id ON events(venue_id);
