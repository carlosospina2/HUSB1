-- -----------------------------------------------------------------------------
-- Tabla: categories
-- Clasificación temática de los eventos.
-- Ejemplos: Conciertos, Talleres, Conferencias, Deportes,
--           Gastronomía, Festivales, Teatro.
-- -----------------------------------------------------------------------------
CREATE TABLE categories (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80) NOT NULL,
    description TEXT,

    CONSTRAINT uq_categories_name UNIQUE (name)
);

-- -----------------------------------------------------------------------------
-- Tabla intermedia: events_categories
-- Resuelve la relación N:M entre events y categories.
-- Nombres de tabla y columnas definidos explícitamente (regla técnica HU-SB4).
-- -----------------------------------------------------------------------------
CREATE TABLE events_categories (
    event_id    BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    PRIMARY KEY (event_id, category_id),

    CONSTRAINT fk_ec_event
        FOREIGN KEY (event_id)    REFERENCES events(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_ec_category
        FOREIGN KEY (category_id) REFERENCES categories(id)
        ON DELETE CASCADE
);

-- Índices para JOINs frecuentes en ambas direcciones
CREATE INDEX idx_ec_event_id    ON events_categories(event_id);
CREATE INDEX idx_ec_category_id ON events_categories(category_id);

